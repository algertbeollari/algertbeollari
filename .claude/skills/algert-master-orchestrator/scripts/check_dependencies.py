#!/usr/bin/env python3
"""Flag name collisions and known duplication risks across the registry.

Reads references/skill-registry.json (produced by inventory_skills.py —
run that first) and reports:
  1. Exact-name collisions: the same skill `name` appearing under more than
     one namespace. A routing rule must pick one, or the orchestrator will
     non-deterministically pick whichever loads first.
  2. Known off-disk duplicates: namespaces this script cannot see on this
     machine's filesystem (e.g. a built-in catalogue mirror) but that chat
     context says exist in parallel to an on-disk namespace. These are
     recorded by hand below, dated, and must be re-verified periodically —
     they are not discovered automatically.

Writes references/dependency-conflicts.md.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ORCH_DIR = Path(__file__).resolve().parents[1]

# Hand-recorded, dated observation: in this chat session (2026-10-13), the
# tool listing advertised `anthropic-skills:dfsa-*` as available, mirroring
# `algert-compliance-skills:dfsa-*` almost one-for-one, but no
# `anthropic-skills` directory exists under ~/.claude/plugins/synced on this
# machine — so inventory_skills.py cannot see or diff its actual content.
# Re-check this list whenever the orchestrator is re-validated; do not trust
# it to still be accurate.
KNOWN_OFF_DISK_SHADOW_NAMESPACES = {
    "anthropic-skills": {
        "shadows": "algert-compliance-skills",
        "observed": "2026-10-13",
        "note": (
            "Appears in the Claude-side available-skills listing with "
            "near-identical dfsa-* names plus a few extras not present in "
            "algert-compliance-skills (seen: dfsa-client-assets-crisis-pack, "
            "dfsa-governance-manual-control, dfsa-quarterly-client-assets-cmp). "
            "Treat algert-compliance-skills as canonical per routing-rules.md "
            "until this is reconciled by hand."
        ),
    }
}


def main() -> None:
    registry_path = ORCH_DIR / "references" / "skill-registry.json"
    if not registry_path.exists():
        raise SystemExit(
            "skill-registry.json not found — run inventory_skills.py first."
        )
    entries = json.loads(registry_path.read_text(encoding="utf-8"))

    by_name: dict[str, list[dict]] = defaultdict(list)
    for e in entries:
        by_name[e["name"]].append(e)

    collisions = {
        name: group for name, group in by_name.items() if len(group) > 1
    }

    lines = []
    lines.append("# Dependency / Conflict Report — generated by check_dependencies.py")
    lines.append("")
    lines.append(
        "Generated, not hand-maintained. Re-run after inventory_skills.py "
        "whenever the registry changes."
    )
    lines.append("")
    lines.append(f"- Exact-name collisions found: **{len(collisions)}**")
    lines.append(
        f"- Known off-disk shadow namespaces on record: "
        f"**{len(KNOWN_OFF_DISK_SHADOW_NAMESPACES)}** (see below — these are "
        "manually recorded, not auto-discovered)"
    )
    lines.append("")

    if collisions:
        lines.append("## Exact-name collisions")
        lines.append("")
        lines.append(
            "Each row is one skill `name` claimed by more than one namespace. "
            "routing-rules.md must state which namespace wins for each; "
            "until it does, treat the skill as **blocked for automated "
            "routing** and ask the owner."
        )
        lines.append("")
        for name in sorted(collisions):
            group = collisions[name]
            namespaces = ", ".join(
                f"`{e['source_type']}:{e['namespace']}`" for e in group
            )
            lines.append(f"- **`{name}`** — claimed by: {namespaces}")
        lines.append("")
    else:
        lines.append("## Exact-name collisions")
        lines.append("")
        lines.append("None found on this machine's filesystem at last run.")
        lines.append("")

    lines.append("## Known off-disk shadow namespaces (manually recorded)")
    lines.append("")
    lines.append(
        "These cannot be detected by scanning this filesystem — they live "
        "somewhere this script has no visibility into (a different sync "
        "mechanism, a different machine). Recorded here so the gap is "
        "explicit rather than silently assumed away."
    )
    lines.append("")
    for ns, info in KNOWN_OFF_DISK_SHADOW_NAMESPACES.items():
        lines.append(f"### `{ns}`")
        lines.append(f"- Shadows: `{info['shadows']}`")
        lines.append(f"- Last observed: {info['observed']}")
        lines.append(f"- Note: {info['note']}")
        lines.append("")

    out_path = ORCH_DIR / "references" / "dependency-conflicts.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path}")
    print(f"Collisions: {len(collisions)}")


if __name__ == "__main__":
    main()
