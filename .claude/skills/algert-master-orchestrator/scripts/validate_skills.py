#!/usr/bin/env python3
"""Validate that every discovered skill has usable frontmatter.

Reads references/skill-registry.json (run inventory_skills.py first) and
checks each entry for:
  - a non-empty `name`
  - a non-empty `description` (routing cannot work on an unlabelled skill)
  - a `name` that is filesystem/URL-safe (lowercase, digits, hyphens only) —
    SKILL.md frontmatter names that break this convention cause silent
    mis-routing in some harnesses rather than a loud error

Writes references/validation-report.md. Exits non-zero if any entry fails,
so it can be wired into a pre-commit or CI check later (Phase 5 of the
rollout plan) without extra work.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ORCH_DIR = Path(__file__).resolve().parents[1]
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")


def validate(entries: list[dict]) -> tuple[list[dict], list[str]]:
    problems: list[dict] = []
    for e in entries:
        issues = []
        name = e.get("name", "")
        desc = e.get("description", "")
        if not name:
            issues.append("missing name")
        elif not NAME_RE.match(name):
            issues.append(f"name '{name}' is not lowercase/hyphen-safe")
        if not desc:
            issues.append("missing description (cannot be routed to safely)")
        elif len(desc) < 15:
            issues.append("description under 15 chars (too thin to route on)")
        if issues:
            problems.append({**e, "issues": issues})
    return problems, []


def main() -> int:
    registry_path = ORCH_DIR / "references" / "skill-registry.json"
    if not registry_path.exists():
        print("skill-registry.json not found — run inventory_skills.py first.")
        return 2
    entries = json.loads(registry_path.read_text(encoding="utf-8"))
    problems, _ = validate(entries)

    lines = []
    lines.append("# Validation Report — generated by validate_skills.py")
    lines.append("")
    lines.append(f"- Entries checked: **{len(entries)}**")
    lines.append(f"- Entries with issues: **{len(problems)}**")
    lines.append("")
    if problems:
        lines.append("| name | namespace | path | issues |")
        lines.append("|---|---|---|---|")
        for p in problems:
            lines.append(
                f"| `{p.get('name','—')}` | `{p['source_type']}:{p['namespace']}` "
                f"| `{p['path']}` | {'; '.join(p['issues'])} |"
            )
    else:
        lines.append("No issues found at last run.")
    lines.append("")

    out_path = ORCH_DIR / "references" / "validation-report.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path}")
    print(f"Checked {len(entries)}, {len(problems)} with issues")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
